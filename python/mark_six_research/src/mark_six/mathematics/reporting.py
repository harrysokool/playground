def write_mathematics_reports(project_root: Path) -> tuple[Path, ...]:
    """Write all deterministic Phase 4 Markdown reports."""

    report_dir = project_root / "reports" / "generated"
    outputs = (
        (report_dir / "prize_probabilities.md", render_prize_probability_report()),
        (report_dir / "current_game_mathematics.md", render_current_game_mathematics_report()),
        (report_dir / "expected_value_foundation.md", render_expected_value_foundation_report()),
    )
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return tuple(path for path, _ in outputs)
