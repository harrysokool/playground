            "",
            "Expected payout per ticket is the sum, over mutually exclusive prize outcomes, of "
            "`probability * dividend`. Net expected value additionally subtracts ticket cost. An "
            "exact probability does not make an unknown future dividend exact.",
            "",
            "## Fixed components",
            "",
            *fixed_lines,
