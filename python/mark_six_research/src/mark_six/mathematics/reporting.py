def _fraction_text(value: Fraction) -> str:
    return f"{value.numerator}/{value.denominator}"


def _decimal_text(value: Fraction, places: int = 12) -> str:
    with localcontext() as context:
        context.prec = 40
        decimal = Decimal(value.numerator) / Decimal(value.denominator)
    return f"{decimal:.{places}f}"


def _one_in_text(value: Fraction) -> str:
    if value.denominator == 1:
        return f"1 in {value.numerator:,}"
    return f"1 in {_decimal_text(value, 6)} (exactly {_fraction_text(value)})"


def _hkd_text(cents: Fraction) -> str:
    return f"HKD {_decimal_text(cents / 100, 6)} (exactly {_fraction_text(cents)} cents)"


def _table(odds: tuple[OutcomeOdds, ...]) -> list[str]:
    lines = [
        "| Outcome | Winning combinations | Exact probability | Decimal probability | Odds "
        "| Derivation |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for item in odds:
        label = item.outcome.replace("_", " ").title()
        lines.append(
            f"| {label} | {item.winning_combinations:,} | `{_fraction_text(item.probability)}` "
            f"| {_decimal_text(item.probability)} | {_one_in_text(item.one_in)} "
            f"| `{item.derivation}` |"
        )
    return lines


def render_prize_probability_report() -> str:
    """Render the complete report without reading draw outcomes or using randomness."""

    current_odds = prize_outcome_odds(49, 7)
    first = current_odds[0]
    official_matches = first.one_in == OFFICIAL_FIRST_DIVISION_ONE_IN
    lines = [
        "# Exact Mark Six Prize Probabilities",
        "",
        "**Generated by:** `mark-six mathematics prize-probabilities`  ",
        "**Arithmetic:** exact integers and rational fractions; no simulation  ",
        "**Scope:** rule mathematics only; no draw-frequency or predictive analysis",
        "",
        "## Method",
        "",
        "Fix six main numbers and one distinct Extra Number from a pool of `N`. Every ordinary "
        "ticket is one of `C(N,6)` equally likely six-number sets. Each row below counts tickets "
        "with the required main-number overlap and Extra Number inclusion. Rows are mutually "
        "exclusive. `No Prize` is the exact complement of the applicable prize rows.",
        "",
        "## Current 6/49, seven-division model",
        "",
        *_table(current_odds),
        "",
        f"Exact probability sum including No Prize: `1/1`. Total ticket universe: "
        f"`C(49,6) = {sum(item.winning_combinations for item in current_odds):,}`.",
        "",
        "## Independent official check",
        "",
        "HKJC publishes First Division odds of 1 in 13,983,816. The independently derived value "
        f"is {_one_in_text(first.one_in)}: **{'MATCH' if official_matches else 'DIFFERENCE'}**. "
        "No rounding is involved in this comparison. Current HKJC prize-qualification material "
        "also independently confirms the seven mutually exclusive winning patterns used above.",
        "",
        "Official sources:",
        "",
        "- [HKJC Mark Six fun facts (published First Division odds)]"
        "(https://campaigns.hkjc.com/2026-marksix/en/funfacts)",
        "- [HKJC prize qualifications]"
        "(https://special.hkjc.com/e-win/en-US/betting-info/marksix/prize-qualification/)",
        "- [HKJC Multiple and Banker chance table]"
        "(https://special.hkjc.com/e-win/en-US/betting-info/marksix/chance-table/)",
        "",
        "## Rule-version model catalogue",
        "",
        "These tables are mathematical consequences of the stated pool and qualification model. "
        "They do not turn an unresolved historical boundary or unverified historical prize rule "
        "into a fact.",
        "",
    ]
    for model in MATHEMATICAL_MODELS:
        odds = prize_outcome_odds(model.pool_size, model.prize_divisions)
        lines.extend(
            (
                f"### {model.label}",
                "",
                model.evidence_note,
                "",
                "Rule registry mappings:",
                "",
                *(f"- `{rule_id}`" for rule_id in model.rule_version_ids),
                "",
                *_table(odds),
                "",
                f"Exact probability sum including No Prize: `1/1`. Total ticket universe: "
                f"`C({model.pool_size},6) = "
                f"{sum(item.winning_combinations for item in odds):,}`.",
                "",
            )
        )
    registry_ids = set(RULE_VERSIONS)
    mapped_ids = {rule_id for model in MATHEMATICAL_MODELS for rule_id in model.rule_version_ids}
    if mapped_ids != registry_ids:
        raise RuntimeError("mathematical model mapping must cover the complete rule registry")
    lines.extend(
        (
            "## Interpretation limits",
            "",
            "- `hkjc_mark_six_1996_pool_transition_unresolved` deliberately maps to both the 6/45 "
            "and 6/47 candidate tables. A draw-level calculation in 1996 must not choose between "
            "them without evidence of the applicable pool.",
            "- Historical tables assume the same six-main/one-Extra qualification patterns shown. "
            "The registry's partial-verification status remains authoritative where archived "
            "formal rules have not been located.",
            "- Multiple and Banker entries are collections of unique ordinary combinations. Their "
            "First Division probability is covered combinations divided by `C(N,6)`; shared-number "
            "tickets are not treated as independent events.",
            "- Prize probability is separate from payout. Divisions 1-3 are variable under current "
            "rules; fixed values and supplied dividends belong in the payout model, not in these "
            "probability calculations.",
            "",
        )
    )
    return "\n".join(lines)


def write_prize_probability_report(path: Path) -> Path:
    """Write the deterministic probability report and return its path."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_prize_probability_report(), encoding="utf-8")
    return path


